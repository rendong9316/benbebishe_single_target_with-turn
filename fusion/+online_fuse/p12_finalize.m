% =========================================================================
% p12_finalize.m — BC 互协方差的可行性投影、保底缩放与对角钳制
% =========================================================================
%
% 【功能概述】
%   对递推得到的 P12 做三件事，保证 BC 数值上站得住：
%
%   1) 归一化：把 P12 变换到"相关度"空间
%        C = P1^{-1/2} * P12 * P2^{-1/2}
%      C 的奇异值天然无量纲：1 表示两站估计完全相关，0 表示互不相关。
%      P1、P2 的量纲差好几个数量级（位置 deg 与速度 deg/s 混在一起），
%      直接在 P12 上比较大小没有意义，因此所有判据都在 C 上做。
%
%   2) 保底缩放：||C||_F / sqrt(n) 不低于 bc_min_p12_scale。
%      批处理线用启发式递推把 P12 逐帧压到接近 0（共享过程噪声比单站
%      协方差小 4~5 个数量级），BC 因此退化成 SCC。这里给相关度一个
%      下限，保证 BC 始终是"真 BC"。放大时保持奇异向量不变，
%      即只改幅度、不改各维度之间的相关结构。
%
%   3) Cauchy–Schwarz 可行性 + 对角钳制（契约 4.2 节）：
%        奇异值裁剪到不大于 1，保证 P12 与 P1、P2 相容；
%        P12(i,i) 不超过 0.8*min(P1(i,i), P2(i,i))。
%
% 【输入参数】
%   P12       — [4x4] 递推得到的互协方差
%   P1, P2    — [4x4] 两站协方差
%   min_scale — 保底相关度（默认 0.05）
%
% 【输出参数】
%   P12 — 处理后的互协方差
% =========================================================================

function P12 = p12_finalize(P12, P1, P2, min_scale)
    if isempty(min_scale)
        min_scale = 0.05;
    end

    % -----------------------------------------------------------------
    % 0) 对称化与数值兜底
    % -----------------------------------------------------------------
    P12 = 0.5 * (P12 + P12');
    if any(isnan(P12(:))) || any(isinf(P12(:)))
        P12 = zeros(size(P12));
        return;
    end

    S1 = psd_sqrt(P1);
    S2 = psd_sqrt(P2);

    % -----------------------------------------------------------------
    % 1) 变换到相关度空间 C = P1^{-1/2} * P12 * P2^{-1/2}
    % -----------------------------------------------------------------
    C = mldivide(S1, P12) / S2;
    C = 0.5 * (C + C');

    % -----------------------------------------------------------------
    % 2) 保底缩放 + Cauchy–Schwarz 裁剪（奇异值）
    % -----------------------------------------------------------------
    [U, S, V] = svd(C);
    s = diag(S);
    n = numel(s);
    nrm = norm(s);
    target = min_scale * sqrt(n);
    if nrm < target
        if nrm > 0
            % 保持奇异向量不变，只按比例放大奇异值
            s = s * (target / nrm);
        else
            % 完全退化（P12 恰为 0）：给一个各向同性的下限相关
            s = target * ones(n, 1);
        end
    end
    % Cauchy–Schwarz：奇异值不超过 1
    s = min(s, 1);
    C = U * diag(s) * V';

    % -----------------------------------------------------------------
    % 3) 变回原坐标
    % -----------------------------------------------------------------
    P12 = S1 * C * S2;
    P12 = 0.5 * (P12 + P12');

    % -----------------------------------------------------------------
    % 4) 对角钳制：P12(i,i) 不超过 0.8*min(P1(i,i), P2(i,i))
    % -----------------------------------------------------------------
    limit = 0.8 * min([diag(P1), diag(P2)], [], 2);
    for i = 1:4
        if P12(i, i) > limit(i)
            scale = sqrt(limit(i) / max(P12(i, i), eps));
            P12(i, :) = P12(i, :) * scale;
            P12(:, i) = P12(:, i) * scale;
        end
    end
end

% =====================================================================
function A = psd_sqrt(P)
%PSD_SQRT 对称半正定矩阵的主平方根
%   用特征分解实现（比 sqrtm 更稳更快）；对接近奇异的特征值做下限保护，
%   保证后续的左除不会因奇异而失败。
    P = 0.5 * (P + P');
    [V, D] = eig(P);
    d = diag(D);
    dmax = max(d);
    if dmax <= 0
        A = zeros(size(P));
        return;
    end
    d = max(d, 1e-12 * dmax);
    A = V * diag(sqrt(d)) * V';
    A = 0.5 * (A + A');
end
