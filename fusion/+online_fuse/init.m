% =========================================================================
% init.m — 在线航迹融合状态初始化
% =========================================================================
%
% 【功能概述】
%   创建逐帧融合（SCC / BC / CI / FCI）的状态结构体。
%   与批处理线 fusion/track_fusion_algorithms.m 的区别在于：本状态是
%   "有状态"的——BC 需要跨帧维护互协方差 P12，帧间断时必须清零。
%
% 【调用方式】
%   F = online_fuse.init(method, params);
%   [x, P, F] = online_fuse.fuse_step(F, est1, est2, k, params);
%
% 【输入参数】
%   method — 字符串，融合算法：'scc' / 'bc' / 'ci' / 'fci'（大小写不敏感）
%   params — 参数结构体（只读拷贝到 F.params）
%            可用字段：
%              dt_sec             — 帧间隔（s），默认 30
%              bc_min_p12_scale   — BC 互协方差保底比例（相对 CS 上界），默认 0.05
%              ukf_process_accel_psd_m2_s3 — 推算过程噪声用的加速度谱密度
%
% 【输出】
%   F — 融合状态，字段：
%     method  — 规范化（大写）后的算法名
%     params  — 参数副本（只读）
%     P12     — 最近一次融合所用的跨帧互协方差（4x4，仅 BC 有意义）
%     last_k  — 最近一次融合的帧号
%     pairs   — 逐配对状态（cell 数组），每个元素字段：
%                 key        — 配对键 sprintf('%d|%d', id1, id2)
%                 P12        — 该配对当前的互协方差（4x4）
%                 last_k     — 该配对上次融合的帧号
%                 P1_prev    — 该配对站 1 上一帧的协方差（4x4）
%                 P2_prev    — 该配对站 2 上一帧的协方差（4x4）
%     n_fuse  — 累计融合次数
%     n_reset — 因帧间断触发 P12 置零的次数
%
% 【设计说明】
%   融合中心（tracker/central_track_manager.m）同一时刻可能维护多条系统航迹，
%   每条系统航迹对应一对局部航迹。P12 是"这一对"的属性，不同配对之间
%   不能共用，否则会互相污染，因此按配对键分开存放。
%   F.P12 只是最近一次融合的快照，供诊断与单元测试使用。
%
% 【对应文档】
%   docs/主链路在线化重构契约_20261028.md 第 4 节
% =========================================================================

function F = init(method, params)
    % -----------------------------------------------------------------
    % 参数兜底
    % -----------------------------------------------------------------
    if nargin < 2 || isempty(params)
        params = struct();
    end

    % -----------------------------------------------------------------
    % 方法名规范化：'scc' / 'SCC' 一视同仁
    % -----------------------------------------------------------------
    name = upper(strtrim(char(method)));

    % -----------------------------------------------------------------
    % 逐字段赋值构造结构体（不用 struct('f', {})，避免得到 0x0 结构体数组）
    % -----------------------------------------------------------------
    F = struct();
    F.method = name;
    F.params = params;
    F.P12 = zeros(4, 4);          % 最近一次融合所用的跨帧互协方差
    F.last_k = NaN;              % 最近一次融合的帧号
    F.pairs = {};                % 逐配对状态（cell 数组，元素为结构体）
    F.n_fuse = 0;                % 累计融合次数
    F.n_reset = 0;               % 帧间断触发 P12 置零的次数
end
